"""Verify the personal planner's guided actions and day/routine persistence."""
import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('--url', default='http://127.0.0.1:8015')
args = parser.parse_args()
with sync_playwright() as p:
    browser = p.chromium.launch(channel='chrome', headless=True)
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(args.url)
    expect(page.get_by_role('button', name='+ Add a task')).to_be_enabled()
    page.get_by_label('Planning day', exact=True).fill('2026-10-24')
    expect(page.get_by_role('button', name='+ Add a task')).to_be_enabled()
    expect(page.get_by_role('tab', name='Tasks (0)', exact=True)).to_be_visible()
    assert 'Saturday' in page.locator('.day-navigation').inner_text()
    page.get_by_role('button', name='Plan my day', exact=True).click()
    expect(page.get_by_role('button', name='Confirm plan')).to_have_count(0)
    expect(page.get_by_role('button', name='Preview my day')).to_be_disabled()
    page.get_by_role('button', name='Add a task', exact=True).click()
    page.get_by_label('Task name').fill('Prepare my presentation')
    page.get_by_label('Duration (minutes)').fill('60')
    page.get_by_role('button', name='Save task', exact=True).click()
    expect(page.get_by_role('button', name='Preview my day')).to_be_enabled()
    page.get_by_role('button', name='Preview my day').click()
    expect(page.get_by_role('button', name='Confirm plan')).to_be_visible()
    expect(page.get_by_label('Planning day', exact=True)).to_be_disabled()
    page.reload()
    expect(page.get_by_role('button', name='Confirm plan')).to_be_visible()
    page.get_by_role('button', name='Cancel', exact=True).click()
    expect(page.get_by_role('tab', name='Timeline (0)', exact=True)).to_be_visible()
    page.get_by_role('button', name='Plan my day', exact=True).click()
    page.get_by_role('button', name='Preview my day').click()
    page.get_by_role('button', name='Confirm plan').click()
    expect(page.get_by_role('tab', name='Timeline (1)', exact=True)).to_be_visible()
    page.get_by_role('button', name='Add an interruption', exact=True).click()
    expect(page.get_by_label('Event name')).to_have_value('')
    expect(page.get_by_label('Start time')).to_have_value('')
    expect(page.get_by_role('button', name='Confirm plan')).to_have_count(0)
    page.get_by_label('Event name').fill('Call with Alex')
    page.get_by_label('Start time').fill('09:30')
    page.get_by_label('End time').fill('10:00')
    page.get_by_role('button', name='Preview fixed event').click()
    page.get_by_role('button', name='Confirm plan').click()
    expect(page.get_by_role('tab', name='Timeline (2)', exact=True)).to_be_visible()
    page.get_by_role('button', name='Fixed plan / routine', exact=True).click()
    page.get_by_label('Routine name').fill('Weekend learning')
    for label in ['Tue', 'Sat', 'Sun']:
        page.get_by_label(label, exact=True).check()
    page.get_by_label('Task 1', exact=True).fill('Read a chapter')
    page.get_by_label('Minutes', exact=True).fill('30')
    page.get_by_role('button', name='Save routine', exact=True).click()
    expect(page.get_by_text('Weekend learning', exact=True)).to_be_visible()
    expect(page.get_by_role('tab', name='Tasks (2)', exact=True)).to_be_visible()
    page.get_by_role('button', name='Close routines').click()
    page.get_by_label('Planning day', exact=True).fill('2026-10-25')
    expect(page.get_by_role('tab', name='Tasks (1)', exact=True)).to_be_visible()
    expect(page.get_by_role('tab', name='Timeline (0)', exact=True)).to_be_visible()
    page.reload()
    expect(page.get_by_role('tab', name='Tasks (1)', exact=True)).to_be_visible()
    page.get_by_label('Planning day', exact=True).fill('2026-10-26')
    expect(page.get_by_role('tab', name='Tasks (0)', exact=True)).to_be_visible()
    page.get_by_label('Planning day', exact=True).fill('2026-10-24')
    expect(page.get_by_role('tab', name='Tasks (2)', exact=True)).to_be_visible()
    expect(page.get_by_role('tab', name='Timeline (2)', exact=True)).to_be_visible()
    assert page.get_by_text('Tool Execution Trace', exact=False).count() == 0
    out = Path('data/personal-days'); out.mkdir(parents=True, exist_ok=True)
    page.screenshot(path=str(out / 'desktop.png'), full_page=True)
    for width in [320, 390, 768, 1024, 1440]:
        page.set_viewport_size({'width': width, 'height': 844})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
    page.set_viewport_size({'width': 390, 'height': 844})
    page.screenshot(path=str(out / 'mobile.png'), full_page=True)
    assert not errors, errors
    browser.close()
print('PASS: empty start; guided planning; review/reload/cancel/confirm; named interruption; weekday routine; day isolation; persistence; 320-1440px; no browser exceptions')
