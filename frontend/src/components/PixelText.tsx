/** Accessible, crisp pixel lettering for short display labels and numbers. */
export default function PixelText({ children }: { children: string }) {
  return <span className="pixel-text" aria-label={children}>{children.split(' ').map((word, index) => {
    const width = Math.max(1, word.length * 6 - 1);
    const path = [...word.toUpperCase()].flatMap((char, letter) => (glyphs[char] ?? '').split('/').flatMap((row, y) =>
      [...row].flatMap((cell, x) => cell === '1' ? [`M${letter * 6 + x} ${y}h1v1h-1z`] : []))).join('');
    return <span className="pixel-word" key={index}><svg aria-hidden="true" viewBox={`0 0 ${width} 7`} style={{ width: `${width / 7}em` }} shapeRendering="crispEdges"><path d={path} fill="currentColor" /></svg></span>;
  })}</span>;
}
